#!/usr/bin/env python3
"""Generates tests/api/roblox_api.luau from Roblox's API dump, so the headless mock can reject
property and member names that don't exist on a class (Roblox throws "X is not a valid member of
Y" for those, but a plain mock silently accepts them).

Usage:  python3 tools/gen_roblox_api.py [Full-API-Dump.json]
Without an argument the dump is downloaded from the Roblox-Client-Tracker mirror.
"""
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = "https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/Full-API-Dump.json"
OUT = os.path.join(ROOT, "tests", "api", "roblox_api.luau")


def security(m, key):
    s = m.get("Security", "None")
    return s.get(key, "None") if isinstance(s, dict) else s


def main():
    if len(sys.argv) > 1:
        dump = json.load(open(sys.argv[1], encoding="utf-8"))
    else:
        with urllib.request.urlopen(URL) as r:
            dump = json.load(r)
    lines = ["-- Generated by tools/gen_roblox_api.py from Roblox's Full-API-Dump. Do not edit.",
             "-- members: P = writable property, R = read-only property, F = method, E = event.",
             "-- property type: <kind>:<category initial>:<type name>", "return {"]
    for c in sorted(dump["Classes"], key=lambda c: c["Name"]):
        members = []
        for m in c["Members"]:
            tags = m.get("Tags") or []
            if "NotScriptable" in tags or security(m, "Read") != "None":
                continue
            t = m["MemberType"]
            if t == "Property":
                writable = "ReadOnly" not in tags and security(m, "Write") == "None"
                vt = m["ValueType"]
                members.append((m["Name"], f'{"P" if writable else "R"}:{vt["Category"][0]}:{vt["Name"]}'))
            elif t == "Function":
                members.append((m["Name"], "F"))
            elif t == "Event":
                members.append((m["Name"], "E"))
        body = ",".join(f'["{n}"]="{v}"' for n, v in sorted(members))
        sup = c.get("Superclass") or ""
        lines.append(f'["{c["Name"]}"]={{s="{sup}",m={{{body}}}}},')
    lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT), os.path.getsize(OUT) // 1024, "KB")


if __name__ == "__main__":
    main()
